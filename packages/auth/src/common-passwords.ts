const COMMON = new Set<string>(NUMERIC);
for (const w of WORDS) for (const s of SUFFIXES) COMMON.add(w + s);

/**
 * True for passwords found in breach lists and every guessing tool: a common word with an obvious suffix, or a number run.
 * The check ignores case. It is a small built-in list, not a full breach database; for that, use a service such as Pwned Passwords.
 */
export function isCommonPassword(password: string): boolean {
  if (typeof password !== "string") return false;
  const p = password.toLowerCase().trim();
  if (COMMON.has(p)) return true;
  // One repeated character, or one short pattern repeated, such as "aaaaaaaaaaaa" or "abcabcabcabc".
  return /^(.{1,4})\1{2,}$/.test(p);
}
